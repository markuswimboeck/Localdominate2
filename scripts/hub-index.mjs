#!/usr/bin/env node
/**
 * Writes src/content/articles/hubIndex.ts: for every article linked from a topic hub
 * (src/content/articles/data/*-hub.ts with `hub: true`), the hub it belongs to. An article listed
 * in several hubs gets the first hub in PRIORITY (most specific first). ArticleV4 shows this as
 * "Übersicht" in the article header, so every article links back to its hub.
 *
 * Usage: node scripts/hub-index.mjs        (run after adding or changing a hub)
 */
import fs from "node:fs";
import path from "node:path";
import os from "node:os";
import { fileURLToPath, pathToFileURL } from "node:url";
import { build } from "esbuild";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const DATA = path.join(ROOT, "src/content/articles/data");
const OUT = path.join(ROOT, "src/content/articles/hubIndex.ts");

/** Most specific hub first. faq-hub only links other hubs and is left out. */
const PRIORITY = [
  ["troubleshooting-hub", "Probleme mit dem Google-Profil"],
  ["bewertungen-reputation-hub", "Bewertungen und Reputation"],
  ["google-business-profil-hub", "Google-Unternehmensprofil"],
  ["google-maps-seo-hub", "Google Maps SEO"],
  ["ai-zukunft-hub", "KI-Suche und GEO"],
  ["local-seo-branchen-hub", "Local SEO nach Branche"],
  ["local-seo-staedte-hub", "Local SEO nach Stadt und Land"],
  ["technisches-seo-hub", "Technisches Local SEO"],
  ["content-marketing-hub", "Content Marketing und Links"],
  ["tools-ressourcen-hub", "Vorlagen und Checklisten"],
  ["case-studies-hub", "Fallstudien prüfen"],
];

/** Articles that sit in several hubs but belong to a later one. */
const OVERRIDES = { "ai-falschangaben-korrigieren-2026": "ai-zukunft-hub" };

const tmp = fs.mkdtempSync(path.join(os.tmpdir(), "hub-index-"));
const texts = (a) =>
  a.sections.flatMap((s) =>
    s.blocks.flatMap((b) =>
      b.t === "ul" || b.t === "ol" ? b.items : b.t === "p" || b.t === "note" ? [b.text] : b.t === "steps" ? b.items.map((i) => i.text) : b.t === "table" ? b.rows.flat() : [],
    ),
  );

const map = {};
for (const [hubSlug, label] of PRIORITY) {
  const file = path.join(DATA, `${hubSlug}.ts`);
  if (!fs.existsSync(file)) continue;
  const outfile = path.join(tmp, `${hubSlug}.mjs`);
  await build({ entryPoints: [file], bundle: true, format: "esm", platform: "node", outfile, logLevel: "error" });
  const { default: hub } = await import(pathToFileURL(outfile).href);
  if (!hub.hub) throw new Error(`${hubSlug}: not marked as hub`);
  for (const t of texts(hub)) {
    for (const m of t.matchAll(/\]\(\/blog\/([a-z0-9-]+)\)/g)) {
      const slug = m[1];
      if (slug.endsWith("-hub") || map[slug]) continue;
      if (OVERRIDES[slug] && OVERRIDES[slug] !== hubSlug) continue;
      map[slug] = { slug: hubSlug, label };
    }
  }
}
fs.rmSync(tmp, { recursive: true, force: true });

const lines = Object.keys(map)
  .sort()
  .map((s) => `  ${JSON.stringify(s)}: { slug: ${JSON.stringify(map[s].slug)}, label: ${JSON.stringify(map[s].label)} },`);
fs.writeFileSync(
  OUT,
  `/** Generated by scripts/hub-index.mjs. Do not edit by hand. Article slug → its topic hub. */\n` +
    `export const HUB_OF: Readonly<Record<string, { slug: string; label: string }>> = {\n${lines.join("\n")}\n};\n`,
);
console.log(`hubIndex.ts: ${lines.length} articles mapped to ${PRIORITY.length} hubs`);
